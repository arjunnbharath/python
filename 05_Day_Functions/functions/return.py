#Return -- This Statement is used to end a function and send a result back to the caller

def add (x,y):
    z=x+y
    return z


def sub (x,y):
    z=x-y
    return z


def mul (x,y):
    z=x*y
    return z

def div (x,y):
    z=x/y
    return z

print (add(1,3))
print(sub(1,2))
print(mul(1,5))
print(div(3,5))